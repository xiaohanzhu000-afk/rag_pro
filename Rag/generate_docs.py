"""
生成示例文档脚本
创建两个企业文档用于 RAG 学习案例
"""
from pathlib import Path
from docx import Document


def create_docx():
    """创建企业员工购物及财务支付全流程手册.docx"""
    doc = Document()
    doc.styles['Normal'].font.name = 'SimSun'
    doc.styles['Normal'].font.size = 140000

    doc.add_heading('企业员工购物及财务支付全流程手册', level=0)

    doc.add_heading('第一部分：员工购物流程', level=1)
    doc.add_heading('一、适用范围', level=2)
    doc.add_paragraph(
        '本手册适用于公司各部门因业务需要的物品采购活动，'
        '包括办公用品、设备器材、服务采购等。'
        '所有员工购物行为必须遵守本手册规定的流程和标准。'
    )

    doc.add_heading('二、购物申请', level=2)
    doc.add_paragraph(
        '员工需要购买物品时，应首先填写《物品采购申请表》。'
        '申请表需包含以下内容：物品名称、规格型号、数量、预估金额、用途说明和期望到货日期。'
        '单笔金额超过5000元的采购，需附至少两家供应商的报价对比。'
    )
    doc.add_paragraph(
        '申请表填写完成后，按以下审批流程提交：'
        '金额2000元以下，由部门主管审批；'
        '金额2000-10000元，由部门主管和财务部双重审批；'
        '金额10000元以上，需总经理审批。'
    )

    doc.add_heading('三、供应商选择', level=2)
    doc.add_paragraph(
        '采购人员应根据采购需求，在合格供应商名录中选择供应商。'
        '合格供应商应符合以下条件：具备合法经营资质；产品和服务质量可靠；'
        '价格具有市场竞争力；售后服务完善。'
    )
    doc.add_paragraph(
        '新供应商引入需经过资质审核、样品测试和价格谈判三个环节。'
        '供应商资质审核包括营业执照、税务登记、行业许可证等文件的核验。'
        '新供应商通过审核后，由采购部将其纳入合格供应商名录。'
    )

    doc.add_heading('四、合同签订', level=2)
    doc.add_paragraph(
        '单笔采购金额超过5000元的，须签订书面采购合同。'
        '合同内容应包括：双方主体信息、标的物描述、数量和价格、'
        '交付时间和地点、验收标准和方式、付款方式和期限、违约责任和争议解决方式。'
    )
    doc.add_paragraph(
        '合同签订前须经法务审核。法务应在收到审核请求后三个工作日内完成审核。'
        '合同签订后，原件由财务部统一保管，采购部和申请部门各保留复印件。'
    )

    doc.add_heading('五、验收与入库', level=2)
    doc.add_paragraph(
        '物品到货后，由采购人员会同申请部门指定人员进行验收。'
        '验收内容包括：核对物品名称、规格型号和数量是否与采购合同一致；'
        '检查物品外观是否完好；测试物品功能是否正常。'
    )
    doc.add_paragraph(
        '验收合格后，填写《物品验收单》，办理入库手续。'
        '验收不合格的物品，应及时与供应商沟通退换货事宜。'
        '验收单须经采购人员、验收人员和部门负责人三方签字确认。'
    )

    doc.add_heading('第二部分：财务支付流程', level=1)
    doc.add_heading('六、付款申请', level=2)
    doc.add_paragraph(
        '采购完成后，由采购人员填写《付款申请表》。申请表需附以下材料：'
        '采购申请表、采购合同或订单、物品验收单、供应商开具的合法发票。'
        '所有材料应确保信息一致，金额无误。'
    )
    doc.add_paragraph(
        '付款申请应至少在付款截止日前三个工作日提交。'
        '紧急付款需注明紧急原因，经财务总监特批后方可办理。'
    )

    doc.add_heading('七、发票管理', level=2)
    doc.add_paragraph(
        '供应商必须提供合法有效的增值税专用发票或普通发票。'
        '采购人员收到发票后应仔细核对：发票抬头是否为公司全称；'
        '纳税人识别号是否正确；发票金额是否与合同一致；'
        '发票项目是否与实际采购内容一致。'
    )
    doc.add_paragraph(
        '发票信息有误的，应及时退回供应商重新开具。'
        '发票签收后应在两个工作日内提交财务部。'
        '财务部负责发票的认证、抵扣和归档管理。'
    )

    doc.add_heading('八、审批流程', level=2)
    doc.add_paragraph('财务支付审批实行分级授权制度：')
    doc.add_paragraph(
        '一级审批（金额0-5000元）：部门主管审核 → 财务审核 → 付款\n'
        '二级审批（金额5000-20000元）：部门主管审核 → 财务经理复核 → 分管副总审批 → 付款\n'
        '三级审批（金额20000元以上）：部门主管审核 → 财务经理复核 → 分管副总审批 → 总经理终审 → 付款'
    )

    doc.add_heading('九、支付方式', level=2)
    doc.add_paragraph(
        '公司财务支付主要通过以下方式：'
        '银行转账（对公）：适用于所有供应商付款，为首选支付方式；'
        '支票支付：适用于有特殊要求的供应商；'
        '现金支付：仅限小额零星采购（单笔500元以下），且须两人以上在场。'
    )
    doc.add_paragraph(
        '严禁使用个人账户代收代付公司款项。'
        '财务部应确保所有支付有据可查，资金流向清晰可追溯。'
    )

    doc.add_heading('十、报销管理', level=2)
    doc.add_paragraph(
        '员工因公垫付的费用，可凭有效凭证申请报销。'
        '报销需填写《费用报销单》，附上发票原件和消费小票。'
        '报销应在费用发生后的三十日内提出，逾期不予受理。'
    )
    doc.add_paragraph(
        '差旅费报销标准按公司差旅管理制度执行。'
        '交通费、住宿费、餐饮补贴均有明确限额标准，超出部分由个人承担。'
        '业务招待费报销需注明招待对象、招待目的和参与人员。'
    )

    doc.add_heading('十一、账务处理', level=2)
    doc.add_paragraph(
        '财务部收到完整的付款申请材料后，应在五个工作日内完成账务处理和付款。'
        '所有采购支出应按会计准则正确归类，计入相应的费用科目或资产科目。'
    )
    doc.add_paragraph(
        '月度终了，财务部应编制采购支出汇总表，报分管领导和总经理审阅。'
        '年度终了，应配合审计工作，提供完整的采购和付款记录。'
    )

    doc.add_heading('十二、监督与审计', level=2)
    doc.add_paragraph(
        '公司内部审计部门每季度对采购和支付流程进行抽查审计。'
        '审计重点包括：采购申请是否合规；供应商选择是否公正透明；'
        '合同签订是否规范完整；验收和付款是否按流程执行。'
    )
    doc.add_paragraph(
        '发现违规行为的，按公司《企业行为规范》相关规定处理。'
        '涉嫌违法的，移交司法机关处理。'
    )

    doc.add_heading('十三、附则', level=2)
    doc.add_paragraph(
        '本手册由财务部和采购部共同制定，由总经理办公室批准发布。'
        '本手册自发布之日起执行，原有相关规定同时废止。'
        '本手册的最终解释权归财务部所有。'
    )

    DATA_DIR = Path(__file__).parent   # 文档直接放在 Rag/ 目录下
    DATA_DIR.mkdir(parents=True, exist_ok=True)
    path = DATA_DIR / "企业员工购物及财务支付全流程手册.docx"
    doc.save(str(path))
    print(f"[OK] DOCX 文件已创建: {path}")


if __name__ == "__main__":
    create_docx()
